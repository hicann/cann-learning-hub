"""
思考题 1 参考答案：自检脚本为何优先读取安装信息文件而非调用 acl.get_version()？

答案说明：
    安装信息文件（ascend_toolkit_install.info）是 CANN 安装时直接写入的，
    包含精确的版本号（如 8.0.0、9.0.0），是最权威的版本来源。

    而 acl.get_version() 返回的是运行时库版本，存在元组映射机制：
    - 元组首元素 1 对应 CANN 6.x
    - 元组首元素 2 对应 CANN 7.x
    - ...
    这种映射关系不直观，容易产生歧义。

    因此，优先读取安装信息文件可以获得更准确、更直观的版本信息。
"""

print("思考题 1 答案：")
print("自检脚本优先读取安装信息文件的原因：")
print("  1. 安装信息文件是安装时直接写入的，版本号精确且直观（如 9.0.0）")
print("  2. acl.get_version() 存在元组映射机制，版本信息不直观")
print("  3. 安装信息文件不依赖运行时库加载，即使 ACL 未初始化也能读取")
