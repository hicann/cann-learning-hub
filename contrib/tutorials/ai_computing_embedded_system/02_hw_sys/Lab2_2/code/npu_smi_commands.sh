#!/bin/bash
# NPU 状态检查命令集合
# 适用平台：香橙派 AIpro（昇腾 310B4）/ Atlas 910B3
# 运行方式：bash npu_smi_commands.sh

echo "============================================================"
echo "[1] NPU 概览信息 (npu-smi info)"
echo "============================================================"
npu-smi info

echo ""
echo "============================================================"
echo "[2] NPU 设备列表/拓扑信息 (npu-smi info -l)"
echo "============================================================"
npu-smi info -l

echo ""
echo "============================================================"
echo "[3] NPU 资源使用情况 (npu-smi info -t usages -i 0)"
echo "============================================================"
npu-smi info -t usages -i 0

echo ""
echo "============================================================"
echo "[4] NPU 板卡信息 (npu-smi info -t board -i 0)"
echo "============================================================"
npu-smi info -t board -i 0

echo ""
echo "============================================================"
echo "[5] NPU 温度信息 (npu-smi info -t temp -i 0)"
echo "============================================================"
npu-smi info -t temp -i 0

echo ""
echo "============================================================"
echo "[6] NPU 功率信息 (npu-smi info -t power -i 0)"
echo "============================================================"
npu-smi info -t power -i 0

echo ""
echo "============================================================"
echo "[7] NPU 显存信息 (npu-smi info -t memory -i 0)"
echo "============================================================"
npu-smi info -t memory -i 0
